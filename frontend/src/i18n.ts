// 轻量国际化模块：按系统语言自动切换中英文，顶栏可手动切换；本地持久化选择
import { ref, computed, type ComputedRef } from 'vue'
import zhCN from 'ant-design-vue/es/locale/zh_CN'
import enUS from 'ant-design-vue/es/locale/en_US'
import dayjs from 'dayjs'
import 'dayjs/locale/zh-cn'
import 'dayjs/locale/en'

export type Lang = 'zh' | 'en'

const STORAGE_KEY = 'devkit_lang'

// 系统语言检测：优先 localStorage 记住的用户选择，否则探测系统语言
function detectLang(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === 'zh' || saved === 'en') return saved
  const sys = (navigator.language || 'zh').toLowerCase()
  return sys.startsWith('zh') ? 'zh' : 'en'
}

const lang = ref<Lang>(detectLang())

function applyLang(l: Lang) {
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
  dayjs.locale(l === 'zh' ? 'zh-cn' : 'en')
  try {
    localStorage.setItem(STORAGE_KEY, l)
  } catch (e) {
    /* 忽略存储异常 */
  }
}

applyLang(lang.value)

const setLang = (l: Lang) => {
  lang.value = l
  applyLang(l)
}

